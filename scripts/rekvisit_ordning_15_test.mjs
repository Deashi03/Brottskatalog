import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import path from 'node:path';
const root=path.resolve(import.meta.dirname,'..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const sw=fs.readFileSync(path.join(root,'service-worker.js'),'utf8');
const srcs=[...html.matchAll(/<script\s+src="([^"]+)"/g)].map(x=>x[1]);
const mod='./rekvisit-ordning-15.js';
assert.ok(srcs.includes(mod)&&sw.includes(mod),'Chapter 16 module must load and be cached offline');
assert.ok(srcs.indexOf(mod)<srcs.indexOf('./stages-08.js'),'Requisites must load before inchoate generation');
const inline=[...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)].map(x=>x[1]);
const ctx=vm.createContext({window:{},console:{warn:()=>{},log:()=>{},error:()=>{}}});
for(const i of [1,2,3])vm.runInContext(inline[i],ctx,{filename:'inline-'+i});
for(const src of srcs)vm.runInContext(fs.readFileSync(path.join(root,src),'utf8'),ctx,{filename:src});
const D=ctx.window.BK_DATA,report=ctx.window.BK_REKVISIT_ORDNING15;
assert.ok(report,'Chapter 16 coverage summary missing');
assert.equal(report.missing.length,0,JSON.stringify(report.missing));
assert.equal(report.mismatch.length,0,JSON.stringify(report.mismatch));
assert.equal(report.missingParent.length,0,JSON.stringify(report.missingParent));
assert.equal(report.added.length+report.already.length,14,'Exactly 14 chapter 16 scope candidates should be accounted for');
const ch=D.crimes.filter(c=>!c.stageType&&c.statute?.startsWith('BrB:16:'));
assert.equal(ch.length,23,'Unexpected chapter 16 baseline count');
assert.equal(ch.filter(c=>!c.rekvisit15?.groups?.length&&!c.rekvisit15?.routes?.length).length,0,'Chapter 16 has structurally missing requisites');
const by=t=>ch.find(c=>c.title===t);
for(const title of [...report.added,...report.already]){
 const c=by(title);assert.ok(c,'Missing '+title);
 assert.equal(c.rekvisit15.legalReviewApproved,false,'Only full independent legal audit can approve '+title);
 assert.ok(c.rekvisit15.sourceURL.includes('riksdagen.se'));
 assert.equal(c.rekvisit15.scope,'lagtext-jamford');
}
assert.equal(by('Barnpornografibrott').rekvisit15.routes.length,5,'Separate manufacture, distribution, sale, brokering and possession/viewing');
const child=JSON.stringify(by('Barnpornografibrott').rekvisit15);
assert.ok(child.includes('pubertetsutvecklingen')&&child.includes('16:10 b')&&child.includes('oaktsam'),'Child age and exemptions cannot be hidden');
assert.equal(by('Myteri').rekvisit15.routes.length,4,'Leadership and actual violence change penalty variants');
assert.equal(by('Olaga våldsskildring').rekvisit15.routes.length,2);
assert.equal(by('Otillåtet förfarande med pornografisk bild').rekvisit15.routes.length,2);
assert.equal(by('Hets mot folkgrupp').rekvisit15.routes.length,2,'Ordinary incitement and special denial provision are distinct');
assert.ok(JSON.stringify(by('Involverande av en underårig i brottslighet').rekvisit15).includes('oaktsamhet'),'Age-negligence alternative mandatory');
assert.ok(JSON.stringify(by('Grovt djurplågeri').rekvisit15).includes('Grov oaktsamhet'),'Fault form cannot be silently upgraded to intent');
const brb=D.crimes.filter(c=>!c.stageType&&c.statute?.startsWith('BrB:'));
const total=brb.filter(c=>c.rekvisit15?.groups?.length||c.rekvisit15?.routes?.length).length;
assert.ok(total>=275,'Need at least 275 structured BrB cards, got '+total);
console.log('PASS V1.5: all 14 remaining BrB chapter 16 requisites and age/exemption safeguards, '+total+'/322 structured BrB cards');
