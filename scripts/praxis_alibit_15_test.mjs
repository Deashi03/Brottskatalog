import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import path from 'node:path';
const root=path.resolve(import.meta.dirname,'..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const sw=fs.readFileSync(path.join(root,'service-worker.js'),'utf8');
const srcs=[...html.matchAll(/<script\s+src="([^"]+)"/g)].map(x=>x[1]);
const mod='./praxis-alibit-15.js';
assert.ok(srcs.includes(mod)&&sw.includes(mod),'New precedent must be loaded and cached offline');
assert.ok(srcs.indexOf(mod)>srcs.indexOf('./brb17-18-fulltext-15.js'));
assert.ok(srcs.indexOf(mod)>srcs.indexOf('./brb15-false-report-requisites-15.js'));
assert.ok(srcs.indexOf(mod)<srcs.indexOf('./stages-08.js'));
const inline=[...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)].map(x=>x[1]);
const ctx=vm.createContext({window:{},console:{log:()=>{},warn:()=>{},error:()=>{}}});
for(const i of [1,2,3])vm.runInContext(inline[i],ctx,{filename:'inline-'+i});
for(const src of srcs)vm.runInContext(fs.readFileSync(path.join(root,src),'utf8'),ctx,{filename:src});
const report=ctx.window.BK_PRAXIS_ALIBIT15;
assert.equal(report.planned,3);
assert.equal(report.annotated,3,JSON.stringify(report));
assert.equal(report.illustrativeCases,1,'Only HD-supported hiding illustration should be added');
assert.equal(report.held.length,0);
const crimes=ctx.window.BK_DATA.crimes,base=crimes.filter(c=>!c.stageType),get=n=>base.find(c=>c.title===n);
for(const name of ['Skyddande av brottsling','Falsk beskyllning','Mened']){
 const c=get(name),p=c.praxisAlibit15;
 assert.ok(p?.sourceURL.includes('domstol.se'),name);
 assert.equal(p.case,'NJA 2019 s. 294');
 assert.equal(p.legalReviewApproved,false);
 assert.equal(p.custodyApproved,false);
 assert.equal(c.rekvisit15.legalReviewApproved,false);
 assert.ok(c.rekvisit15.note.includes('Alibit'));
 assert.equal(c.lawCompletenessVerified,true);
}
assert.ok(get('Skyddande av brottsling').rekvisit15.note.includes('ENDAST påverkar bevisläget'));
assert.ok(get('Falsk beskyllning').rekvisit15.note.includes('15:6'));
assert.ok(get('Mened').rekvisit15.note.includes('ed föreskriven i lag'));
const example=get('Skyddande av brottsling').typexempel15?.[0];
assert.ok(example?.text.includes('gömmer')&&example.sourceURL.includes('domstol.se'));
assert.equal(example.legalReviewApproved,false);
assert.ok(!get('Falsk beskyllning').typexempel15?.length,'Do not invent counterintuitive false allegation typfall');
assert.equal(crimes.length,1473);
assert.equal(crimes.filter(c=>c.stageStatus==='unverified').length,15);
// Negative test: a missing primary text certification must not add a precedent or typecase.
const original=JSON.parse(JSON.stringify({crimes:[get('Skyddande av brottsling')]}));
delete original.crimes[0].praxisAlibit15;
delete original.crimes[0].typexempel15;
const W=JSON.parse(JSON.stringify(ctx.window.BK_STATUTES));
W['BrB:17:11'].complete=false;
const isolated=vm.createContext({window:{BK_DATA:original,BK_STATUTES:W}});
vm.runInContext(fs.readFileSync(path.join(root,mod),'utf8'),isolated);
assert.equal(isolated.window.BK_PRAXIS_ALIBIT15.annotated,0);
assert.equal(isolated.window.BK_PRAXIS_ALIBIT15.illustrativeCases,0);
assert.equal(isolated.window.BK_PRAXIS_ALIBIT15.held.length,3);
assert.equal(original.crimes[0].praxisAlibit15,undefined);
console.log('PASS V1.5: NJA 2019 s. 294 boundary, source-gated illustration and no false criminalization/custody approval');