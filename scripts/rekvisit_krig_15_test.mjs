import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import path from 'node:path';
const root=path.resolve(import.meta.dirname,'..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const sw=fs.readFileSync(path.join(root,'service-worker.js'),'utf8');
const srcs=[...html.matchAll(/<script\s+src="([^"]+)"/g)].map(x=>x[1]);
const mod='./rekvisit-krig-15.js';
assert.ok(srcs.includes(mod)&&sw.includes(mod),'Wartime source module must load offline');
assert.ok(srcs.indexOf(mod)<srcs.indexOf('./stages-08.js'));
const inline=[...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)].map(x=>x[1]);
const ctx=vm.createContext({window:{},console:{log:()=>{},warn:()=>{},error:()=>{}}});
for(const i of [1,2,3])vm.runInContext(inline[i],ctx);
for(const src of srcs)vm.runInContext(fs.readFileSync(path.join(root,src),'utf8'),ctx,{filename:src});
const D=ctx.window.BK_DATA,report=ctx.window.BK_REKVISIT_KRIG15;
assert.ok(report,'Missing wartime requisite summary');
assert.equal(report.missing.length,0,JSON.stringify(report.missing));
assert.equal(report.mismatch.length,0,JSON.stringify(report.mismatch));
assert.equal(report.missingParent.length,0,JSON.stringify(report.missingParent));
assert.equal(report.added.length+report.already.length,18,'All 18 remaining 21–22 chapter offences must be present');
const ch21=D.crimes.filter(c=>!c.stageType&&c.statute?.startsWith('BrB:21:'));
const ch22=D.crimes.filter(c=>!c.stageType&&c.statute?.startsWith('BrB:22:'));
assert.equal(ch21.length,12);
assert.equal(ch22.length,6);
for(const c of [...ch21,...ch22]){
 assert.ok(c.rekvisit15?.routes?.length||c.rekvisit15?.groups?.length,'Wartime requisite structure missing: '+c.title);
 assert.equal(c.rekvisit15.legalReviewApproved,false,'No full legal certification of special military law: '+c.title);
 assert.ok(c.rekvisit15.sourceURL.includes('riksdagen.se'),'Explicit law source required');
}
assert.ok(ch21.every(c=>c.rekvisit15.note.includes('21:1–4')&&c.rekvisit15.note.includes('krig')),'All 21 offences must carry activation/scope warning');
const by=t=>D.crimes.find(c=>!c.stageType&&c.title===t);
assert.equal(by('Undergrävande av stridsviljan').rekvisit15.routes.length,2);
assert.equal(by('Obehörig kapitulation').rekvisit15.routes.length,2);
assert.equal(by('Svikande av försvarsplikt').rekvisit15.routes.length,2);
assert.equal(by('Olovlig befattning med kemiska vapen').rekvisit15.routes.length,2);
assert.equal(by('Olovlig befattning med minor').rekvisit15.routes.length,1);
assert.ok(JSON.stringify(by('Landsskadlig vårdslöshet').rekvisit15).includes('oaktsamhet'));
assert.ok(JSON.stringify(by('Tjänstebrott').rekvisit15).includes('Grov oaktsamhet'));
assert.ok(JSON.stringify(by('Grov olovlig befattning med minor').rekvisit15).includes('Konventionsundantaget'));
assert.ok(by('Olovlig befattning med minor').rekvisit15.routes[0].groups.some(g=>g.label.includes('INTE generellt villkorat')));
assert.ok(by('Olovlig befattning med kemiska vapen').rekvisit15.note.includes('krigsförbrytelsekonkurrens'));
const stages=D.crimes.filter(c=>c.stageType);
assert.equal(stages.filter(c=>c.stageStatus==='unverified').length,0,'Current-stage source classifications must remain independently evidenced');
const brb=D.crimes.filter(c=>!c.stageType&&c.statute?.startsWith('BrB:'));
const total=brb.filter(c=>c.rekvisit15?.groups?.length||c.rekvisit15?.routes?.length).length;
assert.ok(total>=315,'Expected at least 315/319 structured BrB cards, got '+total);
console.log('PASS V1.5: BrB 21/22 war-time scope, inchoate hold and exemptions, '+total+'/'+brb.length+' structured');
