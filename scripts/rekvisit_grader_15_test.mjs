import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import path from 'node:path';
const root=path.resolve(import.meta.dirname,'..'),html=fs.readFileSync(path.join(root,'index.html'),'utf8'),sw=fs.readFileSync(path.join(root,'service-worker.js'),'utf8');
const scripts=[...html.matchAll(/<script\s+src="([^"]+)"/g)].map(x=>x[1]);
for(const name of ['./rekvisit-typexempel-15.js','./rekvisit-core-15.js','./rekvisit-grader-15.js'])assert.ok(scripts.indexOf(name)<scripts.indexOf('./stages-08.js'),'Grade repair must precede stage generator');
assert.ok(sw.includes('./rekvisit-grader-15.js'));
const inline=[...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)].map(x=>x[1]);
const ctx=vm.createContext({window:{},console:{log:()=>{},warn:()=>{},error:()=>{}}});
for(const i of [1,2,3])vm.runInContext(inline[i],ctx);
for(const s of scripts)vm.runInContext(fs.readFileSync(path.join(root,s),'utf8'),ctx,{filename:s});
const all=ctx.window.BK_DATA.crimes,base=all.filter(c=>!c.stageType),stages=all.filter(c=>c.stageType);
const summary=ctx.window.BK_REKVISIT_GRADES15;
assert.ok(summary,'Graded legal requisite module missing');
assert.ok(summary.added>=17,'Expected a material additional tranche of grade requisites, got '+summary.added);
assert.ok(summary.baseAdded>=2,'Basic coercion and home trespass alternatives should be present');
const by=t=>base.find(c=>c.title===t);
for(const title of ['Grov misshandel','Synnerligen grov misshandel','Grovt olaga hot','Grovt hemfridsbrott','Grov stöld','Grovt bedrägeri','Grovt häleri','Grov förskingring','Grov skadegörelse','Grov urkundsförfalskning','Grovt tjänstefel']){
 const c=by(title);
 assert.ok(c,title+' must exist');
 assert.ok(c.rekvisit15?.groups?.length||c.rekvisit15?.routes?.length,'Grade missing statutory requisite groups: '+title);
 assert.equal(c.rekvisit15.legalReviewApproved,false,'No unsupported final legal approval');
 assert.ok(c.rekvisit15.note.includes('helhetsbedömning'),'Grade factors must not be marked individually required');
}
const grovtTjanstefel=by('Grovt tjänstefel');
assert.ok(grovtTjanstefel.rekvisit15.groups.some(g=>g.label.includes('uppsåtligen')),'Aggravated official offence must require intent');
assert.ok(!grovtTjanstefel.rekvisit15.groups.some(g=>g.mode==='any'&&g.label.startsWith('Skuldformen')),'Negligence cannot be sufficient for aggravated official misconduct');
const tystnad=by('Grovt brott mot tystnadsplikt');
if(tystnad)assert.ok(tystnad.rekvisit15.routes.every(r=>r.groups.some(g=>g.label.includes('uppsåtligen'))),'Gross secrecy breach must be intentional');
const invalid=base.filter(c=>c.title==='Grovt olaga frihetsberövande');
assert.equal(invalid.length,0,'BrB 4:2 does not contain a named aggravated offence');
const less=by('Olaga frihetsberövande (mindre grovt fall)');
assert.ok(less,'Preserve underlying record as less serious penalty case');
assert.equal(less.penaltyRange.max,2);
assert.equal(less.penaltyRange.fines,true);
assert.ok(less.skipStageGeneration);
assert.equal(stages.filter(c=>c.stageParentId===less.id).length,0,'No fictional stages to a lesser penalty variant');
const parents=['Olaga tvång','Hemfridsbrott','Olaga intrång'];for(const p of parents)assert.ok(by(p)?.rekvisit15?.routes?.length,'Disjunctive form missing '+p);
const structured=base.filter(c=>c.rekvisit15?.groups?.length||c.rekvisit15?.routes?.length).length;
assert.ok(structured>=56,'Expected broader requisites coverage');
console.log('PASS V1.5: '+summary.added+' graded offence requisite groups; '+structured+' structured base cards; corrected BrB 4:2 and excluded imaginary stage crimes');