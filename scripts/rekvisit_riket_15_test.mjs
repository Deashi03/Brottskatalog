import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import path from 'node:path';
const root=path.resolve(import.meta.dirname,'..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const sw=fs.readFileSync(path.join(root,'service-worker.js'),'utf8');
const srcs=[...html.matchAll(/<script\s+src="([^"]+)"/g)].map(x=>x[1]);
const mod='./rekvisit-riket-15.js';
assert.ok(srcs.includes(mod)&&sw.includes(mod),'BrB 19 module must be available offline');
assert.ok(srcs.indexOf(mod)<srcs.indexOf('./stages-08.js'));
const inline=[...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)].map(x=>x[1]);
const ctx=vm.createContext({window:{},console:{log:()=>{},warn:()=>{},error:()=>{}}});
for(const i of [1,2,3])vm.runInContext(inline[i],ctx);
for(const src of srcs)vm.runInContext(fs.readFileSync(path.join(root,src),'utf8'),ctx,{filename:src});
const data=ctx.window.BK_DATA;
const report=ctx.window.BK_REKVISIT_RIKET15;
assert.ok(report,'Missing BrB 19 legal-scope report');
assert.equal(report.missing.length,0,JSON.stringify(report.missing));
assert.equal(report.mismatch.length,0,JSON.stringify(report.mismatch));
assert.equal(report.missingParent.length,0,JSON.stringify(report.missingParent));
assert.equal(report.added.length+report.already.length,18,'Expected exactly 18 previously unstructured BrB 19 titles');
const ch=data.crimes.filter(c=>!c.stageType&&c.statute?.startsWith('BrB:19:'));
assert.equal(ch.length,20);
assert.equal(ch.filter(c=>!c.rekvisit15?.groups?.length&&!c.rekvisit15?.routes?.length).length,0,'Chapter 19 structural coverage incomplete');
const by=t=>ch.find(c=>c.title===t);
for(const title of [...report.added,...report.already]){
 const c=by(title);assert.ok(c,title);
 assert.equal(c.rekvisit15.legalReviewApproved,false,'Do not misrepresent security offences as legally certified: '+title);
 assert.equal(c.rekvisit15.scope,'lagtext-jamford');
 assert.ok(c.rekvisit15.sourceURL.includes('riksdagen.se'));
 assert.equal(c.typexempel15?.length||0,0,'No invented national-security typfall: '+title);
}
assert.equal(by('Högförräderi').rekvisit15.routes.length,2,'Independence and state-decision cases differ');
assert.equal(by('Utlandsspioneri').rekvisit15.routes.length,2);
assert.equal(by('Obehörig befattning med hemlig uppgift').rekvisit15.routes.length,2);
assert.equal(by('Röjande av hemlig uppgift i internationellt samarbete').rekvisit15.routes.length,2);
assert.equal(by('Egenmäktighet vid förhandling med främmande makt').rekvisit15.routes.length,2,'War/penalty factors are not a third actionable crime route');
const statute=JSON.stringify(by('Utlandsspioneri').rekvisit15);
assert.ok(statute.includes('försvarlig')&&statute.includes('allvarligt men'),'Special exception and seriousness both mandatory');
const vs=JSON.stringify(by('Olovlig underrättelseverksamhet mot främmande makt').rekvisit15);
assert.ok(vs.includes('i landet')&&vs.includes('ANNAN främmande makts'),'Territorial condition and target distinctness mandatory');
const tg=JSON.stringify(by('Tagande av utländskt understöd').rekvisit15);
assert.ok(tg.includes('regeringens förordnande')&&tg.includes('säkerhet'),'Do not suggest all foreign support is a crime');
const all=data.crimes.filter(c=>!c.stageType&&c.statute?.startsWith('BrB:'));
const count=all.filter(c=>c.rekvisit15?.groups?.length||c.rekvisit15?.routes?.length).length;
assert.ok(count>=297,'Expected at least 297/322 structured BrB crimes, got '+count);
console.log('PASS V1.5: 18 BrB 19 distinctions, exceptions and prosecution notes; '+count+'/'+all.length+' structured');
