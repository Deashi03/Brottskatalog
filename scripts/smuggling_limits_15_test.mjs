import assert from 'node:assert/strict';import fs from 'node:fs';import vm from 'node:vm';import path from 'node:path';
const root=path.resolve(import.meta.dirname,'..'),read=p=>fs.readFileSync(path.join(root,p),'utf8');
const html=read('index.html'),mod='./smuggling-limits-15.js',code=read(mod);
const sources=[...html.matchAll(/<script\s+src="([^"]+)"/g)].map(x=>x[1]);
const inline=[...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)].map(x=>x[1]);
const ctx=vm.createContext({window:{},console});
for(const i of [1,2,3])vm.runInContext(inline[i],ctx);
for(const s of sources)if(s!==mod)vm.runInContext(read(s),ctx);
const copy=x=>JSON.parse(JSON.stringify(x)),before=copy(ctx.window.BK_DATA.crimes),doc=copy(ctx.window.BK_SPECIAL_EXCERPTS.SmuglL);
vm.runInContext(code,ctx);
const r=ctx.window.BK_SMUGGLING_LIMITS15,all=ctx.window.BK_DATA.crimes;
assert.equal(r.planned,23);assert.equal(r.explained,23);assert.equal(r.held.length,0);
assert.equal(r.completeExceptionAudits,0);assert.equal(r.completeProsecutionAudits,0);assert.equal(r.fullLegalApprovals,0);
for(const c of all){const clone=copy(c);delete clone.smugglingLimits15;assert.deepEqual(clone,before.find(x=>x.id===c.id),'No changes to legal findings, source certificates, penalties, prosecution or powers');}
assert.equal(all.filter(c=>c.smugglingLimits15).length,23);
assert.equal(all.filter(c=>c.stageType&&c.smugglingLimits15).length,0);
const note=t=>all.find(c=>c.title===t).smugglingLimits15.notes.map(n=>n.text).join('\n');
assert.match(note('Smuggling'),/inte generellt/);
assert.match(note('Tullbrott'),/5 kap\. 5–10 §§/);
assert.match(note('Grovt tullbrott'),/omfattas av rättelseregelns.*men nämns inte/);
assert.match(note('Vårdslös tullredovisning'),/11 § undantar ringa/);
assert.match(note('Olovlig befattning med smuggelgods'),/subsidiär/);
assert.match(note('Grov olovlig befattning med smuggelgods'),/12 § första stycket/);
assert.match(note('Vapensmuggling'),/separat vapenbrott/);
const rerun=(change)=>{const d=copy(doc),a=copy(before);change(d,a);const c=vm.createContext({window:{BK_DATA:{crimes:a},BK_SPECIAL_EXCERPTS:{SmuglL:d}}});vm.runInContext(code,c);return c.window.BK_SMUGGLING_LIMITS15;};
for(const k of ['12','15','20'])assert.equal(rerun(d=>{d.sections[k].text+=' CHANGED';}).explained,0,'Every complete source paragraph is required');
assert.equal(rerun(d=>{d.observedVersion='2099:1';}).explained,0);
assert.equal(rerun(d=>{d.sourceURL='https://example.invalid';}).explained,0);
assert.equal(rerun((d,a)=>{a.find(c=>c.title==='Smuggling').lawCompletenessVerified=false;}).explained,22);
assert.equal(rerun((d,a)=>{a.find(c=>c.title==='Smuggling').lawCompletenessChecked='2099-01-01';}).explained,22);
assert.ok(read('service-worker.js').includes(mod));assert.ok(sources.indexOf(mod)<sources.indexOf('./catalog-selection-15.js'));
assert.ok(html.includes('smuggling-limits'));assert.ok(html.includes('escapeHtml(c.smugglingLimits15.sourceURL)'));
console.log('PASS: 23 source-pinned explanations distinguish voluntary rectification, ringa exceptions, subsidiarity and specific prosecution limits without full legal signoff');
