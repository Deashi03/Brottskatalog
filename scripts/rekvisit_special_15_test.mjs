import assert from 'node:assert/strict';
import fs from 'node:fs';import vm from 'node:vm';import path from 'node:path';
const root=path.resolve(import.meta.dirname,'..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8'),sw=fs.readFileSync(path.join(root,'service-worker.js'),'utf8');
const scripts=[...html.matchAll(/<script\s+src="([^"]+)"/g)].map(m=>m[1]);
assert.ok(scripts.indexOf('./rekvisit-special-15.js')>scripts.indexOf('./rekvisit-grader-15.js'));
assert.ok(scripts.indexOf('./rekvisit-special-15.js')<scripts.indexOf('./stages-08.js'),'Repair titles before stage generation');
assert.ok(sw.includes('./rekvisit-special-15.js'));
const inline=[...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)].map(x=>x[1]);
const ctx=vm.createContext({window:{},console:{log:()=>{},warn:()=>{},error:()=>{}}});
for(const i of [1,2,3])vm.runInContext(inline[i],ctx);
for(const src of scripts)vm.runInContext(fs.readFileSync(path.join(root,src),'utf8'),ctx,{filename:src});
const d=ctx.window.BK_DATA,base=d.crimes.filter(c=>!c.stageType),stage=d.crimes.filter(c=>c.stageType);
const stats=ctx.window.BK_REKVISIT_SPECIAL15;
assert.ok(stats);
assert.ok(stats.updated>=12,'Must introduce at least twelve new source-specific requisite structures');
assert.equal(stats.mismatch.length,0,'No offence may silently inherit mismatched SFS ref '+stats.mismatch.join(', '));
const by=t=>base.find(c=>c.title===t);
for(const title of ['Bokföringsbrott','Penningförfalskning','Osann försäkran','Osant intygande','Föregivande av allmän ställning','Ohörsamhet mot ordningsmakten','Uppvigling','Förargelseväckande beteende','Förolämpning mot tjänsteman']){
 const c=by(title);assert.ok(c,'Crime not found: '+title);
 assert.ok(c.rekvisit15?.groups?.length||c.rekvisit15?.routes?.length,'Missing source-backed elements: '+title);
 assert.equal(c.rekvisit15.legalReviewApproved,false,'Never falsely certify all doctrine/praxis');
}
const grav=by('Gravfridsbrott'),gross=by('Grovt gravfridsbrott');
assert.ok(grav,'Current statutory rubricering Gravfridsbrott must be indexed');
assert.ok(gross,'Distinct aggravated grade must be indexed');
assert.ok(!by('Brott mot griftefrid'),'Obsolete title must be an alias, not a current crime');
assert.equal(grav.shortRef,'BrB 16:10');assert.equal(gross.shortRef,'BrB 16:10');
assert.equal(gross.penaltyRange.min,.5);
assert.equal(gross.penaltyRange.max,4);
assert.ok(grav.rekvisit15?.routes?.length>=2);
assert.ok(grav.aliases?.some(a=>a.toLocaleLowerCase('sv')==='brott mot griftefrid')||grav.id==='v15-gravfridsbrott');
const img=by('Föregivande av allmän ställning');
assert.equal(img.typexempel15?.length,1);
assert.ok(img.typexempel15[0].sourceURL.includes('riksdagen.se'));
const count=base.filter(c=>c.rekvisit15?.groups?.length||c.rekvisit15?.routes?.length).length;
assert.ok(count>=98,'Structured requisite expansion did not sufficiently increase coverage: '+count);
assert.ok(stage.length>1000);
console.log('PASS V1.5: '+stats.updated+' additional source-scoped requisites, '+count+' structured BrB entries, 2022 gravfrid correction and realistic police impersonation typfall');