import assert from 'node:assert/strict';
import fs from 'node:fs';import vm from 'node:vm';import path from 'node:path';
const root=path.resolve(import.meta.dirname,'..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const sw=fs.readFileSync(path.join(root,'service-worker.js'),'utf8');
const mod='./brb15-false-report-requisites-15.js';
const scripts=[...html.matchAll(/<script\s+src="([^"]+)"/g)].map(x=>x[1]);
assert.ok(scripts.includes(mod)&&sw.includes(mod),'BrB 15:6 and 15:7 support must be cached offline');
assert.ok(scripts.indexOf(mod)>scripts.indexOf('./brb-curated-lawtext-15.js'));
assert.ok(scripts.indexOf(mod)<scripts.indexOf('./stages-08.js'));
const inline=[...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)].map(x=>x[1]);
const ctx=vm.createContext({window:{},console:{log:()=>{},warn:()=>{},error:()=>{}}});
for(const i of [1,2,3])vm.runInContext(inline[i],ctx);
for(const src of scripts)vm.runInContext(fs.readFileSync(path.join(root,src),'utf8'),ctx,{filename:src});
const stats=ctx.window.BK_BRB15_FALSE_REPORT_REQUISITES15;
assert.ok(stats);
assert.equal(stats.planned,4);
assert.equal(stats.updated,4,JSON.stringify(stats));
assert.equal(stats.held.length,0);
assert.equal(stats.missing.length,0);
assert.equal(stats.allSourceChecked,true);
assert.equal(stats.coercionAuthorized,false);
assert.equal(stats.stageEntriesModified,0);
const crimes=ctx.window.BK_DATA.crimes;
const by=t=>crimes.find(c=>!c.stageType&&c.title===t);
const a=by('Falsk angivelse'),aNeg=by('Obefogad angivelse'),b=by('Falsk beskyllning'),bNeg=by('Vårdslös beskyllning');
for(const c of [a,aNeg,b,bNeg]){
 assert.ok(c,'Missing false-accusation card');
 assert.equal(c.rekvisit15.legalReviewApproved,false);
 assert.equal(c.rekvisit15.verifiedOn,'2026-10-18');
 assert.ok(c.rekvisit15.sourceURL?.includes('riksdagen.se'));
 assert.ok(c.rekvisit15.note.includes('15:14'));
 assert.ok(c.rekvisit15.note.includes('inte ett automatiskt polisbeslut'));
 assert.ok(c.rekvisit15.groups.length>=3);
}
assert.equal(a.statute,'BrB:15:6');
assert.equal(b.statute,'BrB:15:7');
assert.ok(a.rekvisit15.groups.some(x=>x.label.includes('SÄRSKILDA uppsåtet')));
assert.ok(a.rekvisit15.groups.some(x=>x.label.includes('anges till åtal')));
assert.ok(aNeg.rekvisit15.groups.some(x=>x.label.includes('SKÄLIG ANLEDNING ATT ANTA')));
assert.ok(b.rekvisit15.groups.some(x=>x.label.includes('annat fall än angivelse')));
assert.ok(b.rekvisit15.groups.some(x=>x.label.includes('Polismyndigheten')));
assert.equal(b.rekvisit15.groups.find(x=>x.mode==='any')?.options.length,3);
assert.equal(bNeg.rekvisit15.groups.find(x=>x.mode==='any')?.options.length,3);
assert.ok(bNeg.rekvisit15.groups.some(x=>x.label.includes('SKÄLIG ANLEDNING ATT ANTA')));
const p=ctx.window.BK_STATUTES;
assert.ok(p['BrB:15:6'].text.includes('obefogad angivelse'));
assert.ok(p['BrB:15:7'].text.includes('vårdslös beskyllning'));
assert.ok(p['BrB:15:14'].text.includes('innan avsevärd olägenhet'));
assert.equal(crimes.filter(c=>c.stageType&&c.stageStatus==='unverified').length,15);
// Degraded source cannot overwrite conservative requirements.
const raw=fs.readFileSync(path.join(root,mod),'utf8');
const old={legalReviewApproved:false,groups:[{mode:'all',label:'keep prior'}]};
const fake={title:'Falsk angivelse',statute:'BrB:15:6',rekvisit15:old};
const obj={window:{BK_DATA:{crimes:[fake]},BK_STATUTES:{'BrB:15:6':{complete:false}}},console};
vm.runInNewContext(raw,obj,{filename:mod});
assert.equal(obj.window.BK_BRB15_FALSE_REPORT_REQUISITES15.updated,0);
assert.equal(fake.rekvisit15,old);
console.log('PASS V1.5: false angivelse vs false beskyllning, intent/negligence routes, statutory 15:14 and no unsourced legal authorization');
